/// Image both edges run. Pinned to a major so `AutoUpdate` can follow patch releases.
pub const EDGE_IMAGE: &str = "docker.io/library/caddy:2-alpine";
/// Admin socket inside an edge container; `caddy reload` talks to it.
pub const EDGE_ADMIN_SOCKET: &str = "unix//run/caddy-admin.sock";
/// Where an edge container finds its config (a bind mount of the panel-written file).
pub const EDGE_CONFIG_PATH: &str = "/cfg/edge.json";
/// Host edge: admin API bound on the host's loopback (`Network=host`).
pub const HOST_EDGE_ADMIN: &str = "127.0.0.1:2019";
/// Host edge container name (rootful Quadlet unit `maurice-edge.container`).
pub const HOST_EDGE_CONTAINER: &str = "maurice-edge";

/// Inputs for the workspace edge unit.
pub struct EdgeInput<'a> {
    pub workspace: &'a Workspace,
    /// Internal host address other workspaces reach internal routes on; `None` = loopback only.
    pub internal_addr: Option<std::net::IpAddr>,
    /// Block ports services publish directly (`PublishPort=` in their own units); the
    /// edge leaves those out of its ranges so both can bind.
    pub direct_ports: Vec<u16>,
}

/// Contiguous ranges of the block that are not in `excluded`.
pub fn free_ranges(block: maurice_core::PortBlock, excluded: &[u16]) -> Vec<(u16, u16)> {
    let mut out = Vec::new();
    let mut start: Option<u16> = None;
    for p in block.start..=block.end() {
        if excluded.contains(&p) {
            if let Some(s) = start.take() {
                out.push((s, p - 1));
            }
        } else if start.is_none() {
            start = Some(p);
        }
    }
    if let Some(s) = start {
        out.push((s, block.end()));
    }
    out
}

/// Named volumes of the workspace edge (TLS storage and Caddy's own config dir).
pub fn render_edge_volumes() -> Vec<Unit> {
    ["edge-data", "edge-config"]
        .iter()
        .map(|stem| Unit {
            file_name: format!("{stem}.volume"),
            content: format!(
                "# Generated by Maurice. Edit the model, not this file.\n\
                 [Volume]\n\
                 VolumeName={stem}\n"
            ),
        })
        .collect()
}

/// The workspace edge: one rootless Caddy on every environment network of the
/// workspace, publishing the whole port block once so routes never need a restart.
pub fn render_edge(input: &EdgeInput<'_>) -> Unit {
    let ws = input.workspace;
    let block = ws.port_block;
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Generated by Maurice for {}/edge. Edit the model, not this file.",
        ws.name
    );
    let _ = writeln!(out, "[Unit]");
    let _ = writeln!(out, "Description=Workspace edge for {}", ws.name);
    out.push('\n');
    let _ = writeln!(out, "[Container]");
    let _ = writeln!(out, "ContainerName=edge");
    let _ = writeln!(out, "Image={EDGE_IMAGE}");
    for e in &ws.environments {
        let _ = writeln!(out, "Network={}.network", ws.network_name(e.env));
    }
    for (s, e) in free_ranges(block, &input.direct_ports) {
        let _ = writeln!(out, "PublishPort=127.0.0.1:{s}-{e}:{s}-{e}");
        if let Some(addr) = input.internal_addr {
            let _ = writeln!(out, "PublishPort={addr}:{s}-{e}:{s}-{e}");
        }
    }
    let _ = writeln!(out, "Volume={}/edge:/cfg:Z", ws.home);
    let _ = writeln!(out, "Volume=edge-data.volume:/data:Z");
    let _ = writeln!(out, "Volume=edge-config.volume:/config:Z");
    let _ = writeln!(out, "Exec=caddy run --config {EDGE_CONFIG_PATH}");
    let _ = writeln!(out, "LogDriver=journald");
    let _ = writeln!(out, "Label=maurice.workspace={}", ws.name);
    let _ = writeln!(out, "Label=maurice.unit=edge");
    out.push('\n');
    let _ = writeln!(out, "[Service]");
    let _ = writeln!(out, "Restart=always");
    let _ = writeln!(out, "TimeoutStopSec=30");
    if let Some(slice) = &ws.cpu_slice {
        let _ = writeln!(out, "Slice={slice}");
    }
    out.push('\n');
    let _ = writeln!(out, "[Install]");
    let _ = writeln!(out, "WantedBy=default.target");
    Unit {
        file_name: "edge.container".into(),
        content: out,
    }
}

/// One listener of the workspace edge.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EdgeRoute {
    pub block_port: u16,
    /// `container-name:port`, resolvable on one of the edge's networks.
    pub upstream: String,
}

/// Caddy JSON for the workspace edge: one server per route, admin on a unix socket.
pub fn render_edge_config(routes: &[EdgeRoute]) -> String {
    let mut servers = serde_json::Map::new();
    let mut sorted: Vec<&EdgeRoute> = routes.iter().collect();
    sorted.sort_by_key(|r| r.block_port);
    for r in sorted {
        servers.insert(
            format!("r{}", r.block_port),
            serde_json::json!({
                "listen": [format!(":{}", r.block_port)],
                "automatic_https": {"disable": true},
                "routes": [{
                    "handle": [{
                        "handler": "reverse_proxy",
                        "upstreams": [{"dial": r.upstream}]
                    }]
                }]
            }),
        );
    }
    let config = serde_json::json!({
        "admin": {"listen": EDGE_ADMIN_SOCKET},
        "apps": {"http": {"servers": servers}}
    });
    serde_json::to_string_pretty(&config).expect("static json") + "\n"
}

/// A domain the host edge serves, with the workspace edge port behind it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HostRoute {
    pub domain: String,
    pub public_ip: Option<std::net::IpAddr>,
    pub tls: maurice_core::TlsMode,
    /// Loopback port of the workspace edge listener.
    pub upstream_port: u16,
}

/// Caddy JSON for the host edge: HTTPS servers per public address with host
/// matchers, an HTTP server for plain domains, certificate policies per mode.
pub fn render_host_edge_config(routes: &[HostRoute], acme_email: Option<&str>) -> String {
    use maurice_core::TlsMode;
    let proxy = |port: u16| {
        serde_json::json!([{
            "handler": "reverse_proxy",
            "upstreams": [{"dial": format!("127.0.0.1:{port}")}]
        }])
    };
    let mut servers = serde_json::Map::new();
    let mut https: std::collections::BTreeMap<String, Vec<serde_json::Value>> = Default::default();
    let mut http_routes = Vec::new();
    let mut skip = Vec::new();
    let mut internal = Vec::new();
    let mut acme = Vec::new();
    let mut sorted: Vec<&HostRoute> = routes.iter().collect();
    sorted.sort_by(|a, b| a.domain.cmp(&b.domain));
    for r in sorted {
        let route = serde_json::json!({
            "match": [{"host": [r.domain]}],
            "handle": proxy(r.upstream_port),
            "terminal": true
        });
        match r.tls {
            TlsMode::Off => {
                skip.push(r.domain.clone());
                http_routes.push(route);
            }
            mode => {
                let listen = match r.public_ip {
                    Some(ip) => format!("{ip}:443"),
                    None => ":443".into(),
                };
                https.entry(listen).or_default().push(route);
                if mode == TlsMode::Internal {
                    internal.push(r.domain.clone());
                } else {
                    acme.push(r.domain.clone());
                }
            }
        }
    }
    // Unknown hosts get a plain 404 instead of Caddy's empty 200.
    let not_found = serde_json::json!({
        "handle": [{"handler": "static_response", "status_code": 404, "body": "no such site\n"}]
    });
    for (i, (listen, mut rs)) in https.into_iter().enumerate() {
        rs.push(not_found.clone());
        servers.insert(
            format!("https{i}"),
            serde_json::json!({
                "listen": [listen],
                "routes": rs,
                "automatic_https": {"skip": skip}
            }),
        );
    }
    http_routes.push(not_found);
    servers.insert(
        "http".into(),
        serde_json::json!({
            "listen": [":80"],
            "routes": http_routes,
            "automatic_https": {"skip": skip}
        }),
    );
    let mut policies = Vec::new();
    if !internal.is_empty() {
        policies.push(serde_json::json!({
            "subjects": internal,
            "issuers": [{"module": "internal"}]
        }));
    }
    if !acme.is_empty() {
        let mut issuer = serde_json::json!({"module": "acme"});
        if let Some(email) = acme_email {
            issuer["email"] = serde_json::Value::String(email.into());
        }
        policies.push(serde_json::json!({"subjects": acme, "issuers": [issuer]}));
    }
    let mut config = serde_json::json!({
        "admin": {"listen": HOST_EDGE_ADMIN},
        "apps": {"http": {"servers": servers}}
    });
    if !policies.is_empty() {
        config["apps"]["tls"] = serde_json::json!({"automation": {"policies": policies}});
    }
    serde_json::to_string_pretty(&config).expect("static json") + "\n"
}

/// The rootful host edge unit (`/etc/containers/systemd/maurice-edge.container`).
pub fn render_host_edge_unit(config_dir: &str) -> String {
    format!(
        "# Generated by `maurice host prepare`. The panel rewrites {config_dir}/host.json and reloads.\n\
         [Unit]\n\
         Description=Maurice host edge (Caddy on 80/443)\n\
         After=network-online.target\n\
         Wants=network-online.target\n\
         \n\
         [Container]\n\
         ContainerName={HOST_EDGE_CONTAINER}\n\
         Image={EDGE_IMAGE}\n\
         Network=host\n\
         Volume={config_dir}:/cfg:Z\n\
         Volume=maurice-edge-data:/data:Z\n\
         Volume=maurice-edge-config:/config:Z\n\
         Exec=caddy run --config /cfg/host.json\n\
         LogDriver=journald\n\
         \n\
         [Service]\n\
         Restart=always\n\
         TimeoutStopSec=30\n\
         \n\
         [Install]\n\
         WantedBy=multi-user.target\n"
    )
}

#[cfg(test)]
mod edge_tests {
    use super::*;
    use maurice_core::*;

    fn ws() -> Workspace {
        Workspace {
            name: "shop".into(),
            unix_user: "ws-shop".into(),
            uid: 999,
            subuid_start: 1_000_000,
            subuid_len: 65536,
            home: "/srv/ws/shop".into(),
            cpu_slice: None,
            port_block: PortBlock {
                start: 20000,
                size: 500,
            },
            environments: vec![
                Environment {
                    env: Env::Dev,
                    projects: vec![],
                },
                Environment {
                    env: Env::Prod,
                    projects: vec![],
                },
            ],
        }
    }

    #[test]
    fn edge_unit_publishes_the_block_on_every_network() {
        let u = render_edge(&EdgeInput {
            workspace: &ws(),
            internal_addr: Some("10.200.0.1".parse().unwrap()),
            direct_ports: vec![],
        });
        assert_eq!(u.file_name, "edge.container");
        let c = &u.content;
        assert!(c.contains("Network=shop-dev.network"));
        assert!(c.contains("Network=shop-prod.network"));
        assert!(c.contains("PublishPort=127.0.0.1:20000-20499:20000-20499"));
        assert!(c.contains("PublishPort=10.200.0.1:20000-20499:20000-20499"));
        // Directly published ports are carved out so both units can bind.
        let u = render_edge(&EdgeInput {
            workspace: &ws(),
            internal_addr: None,
            direct_ports: vec![20080, 20000],
        });
        assert!(
            u.content
                .contains("PublishPort=127.0.0.1:20001-20079:20001-20079")
        );
        assert!(
            u.content
                .contains("PublishPort=127.0.0.1:20081-20499:20081-20499")
        );
        assert!(!u.content.contains("10.200.0.1"));
        assert_eq!(free_ranges(ws().port_block, &[20499]), vec![(20000, 20498)]);
        assert!(c.contains("Volume=/srv/ws/shop/edge:/cfg:Z"));
        assert!(c.contains("WantedBy=default.target"));
        assert_eq!(render_edge_volumes().len(), 2);
    }

    #[test]
    fn edge_config_has_one_server_per_route() {
        let json = render_edge_config(&[
            EdgeRoute {
                block_port: 20081,
                upstream: "dev-api-v2:8080".into(),
            },
            EdgeRoute {
                block_port: 20080,
                upstream: "dev-web-16:80".into(),
            },
        ]);
        let v: serde_json::Value = serde_json::from_str(&json).unwrap();
        assert_eq!(v["admin"]["listen"], EDGE_ADMIN_SOCKET);
        let servers = v["apps"]["http"]["servers"].as_object().unwrap();
        assert_eq!(servers.len(), 2);
        assert_eq!(servers["r20080"]["listen"][0], ":20080");
        assert_eq!(
            servers["r20080"]["routes"][0]["handle"][0]["upstreams"][0]["dial"],
            "dev-web-16:80"
        );
        let empty: serde_json::Value = serde_json::from_str(&render_edge_config(&[])).unwrap();
        assert!(
            empty["apps"]["http"]["servers"]
                .as_object()
                .unwrap()
                .is_empty()
        );
    }

    #[test]
    fn host_edge_config_splits_tls_modes() {
        let json = render_host_edge_config(
            &[
                HostRoute {
                    domain: "shop.example.com".into(),
                    public_ip: None,
                    tls: TlsMode::Auto,
                    upstream_port: 20080,
                },
                HostRoute {
                    domain: "shop.test".into(),
                    public_ip: None,
                    tls: TlsMode::Internal,
                    upstream_port: 20080,
                },
                HostRoute {
                    domain: "plain.test".into(),
                    public_ip: Some("203.0.113.5".parse().unwrap()),
                    tls: TlsMode::Off,
                    upstream_port: 20081,
                },
            ],
            Some("ops@example.com"),
        );
        let v: serde_json::Value = serde_json::from_str(&json).unwrap();
        let servers = v["apps"]["http"]["servers"].as_object().unwrap();
        assert_eq!(servers["https0"]["listen"][0], ":443");
        assert_eq!(
            servers["https0"]["routes"].as_array().unwrap().len(),
            3,
            "two domains plus the 404 fallback"
        );
        assert_eq!(
            servers["http"]["routes"][0]["match"][0]["host"][0],
            "plain.test"
        );
        assert_eq!(
            servers["http"]["routes"][1]["handle"][0]["status_code"],
            404
        );
        assert_eq!(servers["http"]["automatic_https"]["skip"][0], "plain.test");
        let policies = v["apps"]["tls"]["automation"]["policies"]
            .as_array()
            .unwrap();
        assert_eq!(policies[0]["issuers"][0]["module"], "internal");
        assert_eq!(policies[1]["issuers"][0]["email"], "ops@example.com");
        assert!(render_host_edge_unit("/etc/maurice/edge").contains("Network=host"));
    }
}
