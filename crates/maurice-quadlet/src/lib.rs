//! Turns the domain model into Quadlet unit files.
//!
//! The output is plain text written into
//! `~/.config/containers/systemd/` of the workspace user. Everything here is a
//! pure function of the model: same input, same bytes, so a unit can be diffed
//! against what is on disk to detect drift.
//!
//! Rules baked in, from the plan:
//! - every environment of a workspace has its own network; unit names are prefixed
//!   with the environment so `prod-web` and `dev-web` coexist under one user
//! - a service is reachable by its alias only; the container name carries the version
//! - no `PublishPort=` unless the port is published, and then on the given host IP
//! - secrets are referenced by name, never inlined
//! - volumes always carry `:Z` so the unit works unchanged on an SELinux host

use maurice_core::{Env, EnvValue, Published, Service, ServiceKind, Source, Workspace};
use std::fmt::Write as _;

/// A rendered unit: where it goes relative to the quadlet directory and its content.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Unit {
    pub file_name: String,
    pub content: String,
}

/// Inputs the renderer needs beyond the model: resolved image and references.
pub struct RenderInput<'a> {
    pub workspace: &'a Workspace,
    /// Environment the service runs in: selects the network and prefixes unit names.
    pub env: Env,
    pub service: &'a Service,
    /// Fully resolved image, preferably by digest: `registry/web@sha256:…`.
    pub image: &'a str,
    /// Short version tag that makes the container name unique: git sha or digest prefix.
    pub version: &'a str,
    /// Resolver for `{{service.field}}` references. Returns `None` when unknown.
    pub resolve_ref: &'a dyn Fn(&str) -> Option<String>,
    /// Start at boot. False until the service has been deployed once, so a defined
    /// but never started service does not come up after a reboot.
    pub enabled: bool,
}

#[derive(Debug, PartialEq, Eq)]
pub enum RenderError {
    UnresolvedRef { key: String, reference: String },
}

impl std::fmt::Display for RenderError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            RenderError::UnresolvedRef { key, reference } => {
                write!(f, "env {key}: reference {reference} could not be resolved")
            }
        }
    }
}
impl std::error::Error for RenderError {}

/// Unit stem of a service in an environment: `prod-web` for `prod-web.container`,
/// `prod-web.service` and the `prod-web-<version>` container name.
pub fn unit_stem(env: Env, service: &str) -> String {
    format!("{env}-{service}")
}

/// An environment's network. One per environment; service names resolve through
/// aardvark-dns, which Quadlet enables by default (verified on Podman 5.7: `DNS=`
/// takes resolver IPs).
pub fn render_network(ws: &Workspace, env: Env) -> Unit {
    let name = ws.network_name(env);
    let content = format!(
        "# Generated by Maurice for {ws}/{env}. Edit the model, not this file.\n\
         [Unit]\n\
         Description=Network for {ws}/{env}\n\
         \n\
         [Network]\n\
         NetworkName={name}\n\
         Internal=false\n",
        ws = ws.name,
    );
    Unit {
        file_name: format!("{name}.network"),
        content,
    }
}

/// Named volume units for a service.
pub fn render_volumes(env: Env, service: &Service) -> Vec<Unit> {
    service
        .volumes
        .iter()
        .filter(|v| !v.source.starts_with('/'))
        .map(|v| {
            let stem = volume_stem(env, service, &v.source);
            Unit {
                file_name: format!("{stem}.volume"),
                content: format!(
                    "# Generated by Maurice. Edit the model, not this file.\n\
                     [Volume]\n\
                     VolumeName={stem}\n"
                ),
            }
        })
        .collect()
}

/// The container unit for a service.
pub fn render_container(input: &RenderInput<'_>) -> Result<Unit, RenderError> {
    let ws = input.workspace;
    let env = input.env;
    let svc = input.service;
    let stem = unit_stem(env, &svc.name);
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Generated by Maurice for {}/{env}/{}. Edit the model, not this file.",
        ws.name, svc.name
    );
    let _ = writeln!(out, "[Unit]");
    let _ = writeln!(
        out,
        "Description={} in {}/{env} ({})",
        svc.name,
        ws.name,
        kind_label(svc.kind)
    );
    // No explicit Requires/After for the network: Quadlet derives them from `Network=`.
    out.push('\n');

    let _ = writeln!(out, "[Container]");
    let _ = writeln!(out, "ContainerName={stem}-{}", input.version);
    let _ = writeln!(out, "Image={}", input.image);
    let _ = writeln!(out, "Network={}.network", ws.network_name(env));
    let _ = writeln!(out, "NetworkAlias={}", svc.name);
    let _ = writeln!(out, "LogDriver=journald");
    let _ = writeln!(out, "Label=maurice.workspace={}", ws.name);
    let _ = writeln!(out, "Label=maurice.environment={env}");
    let _ = writeln!(out, "Label=maurice.service={}", svc.name);
    let _ = writeln!(out, "Label=maurice.unit={stem}");
    let _ = writeln!(out, "Label=maurice.version={}", input.version);

    for p in &svc.ports {
        if let Some(Published { host_ip, host_port }) = p.published {
            let _ = writeln!(
                out,
                "PublishPort={}:{}:{}",
                host_ip, host_port, p.container_port
            );
        }
    }

    for e in &svc.env {
        match &e.value {
            EnvValue::Literal(v) => {
                let _ = writeln!(out, "Environment={}={}", e.key, quote_env(v));
            }
            EnvValue::Ref(r) => {
                let v = (input.resolve_ref)(r).ok_or_else(|| RenderError::UnresolvedRef {
                    key: e.key.clone(),
                    reference: r.clone(),
                })?;
                let _ = writeln!(out, "Environment={}={}", e.key, quote_env(&v));
            }
            EnvValue::Secret(name) => {
                let _ = writeln!(out, "Secret={name},type=env,target={}", e.key);
            }
        }
    }

    for v in &svc.volumes {
        let source = if v.source.starts_with('/') {
            v.source.clone()
        } else {
            format!("{}.volume", volume_stem(env, svc, &v.source))
        };
        let mut opts = String::from("Z");
        if v.read_only {
            opts.push_str(",ro");
        }
        let _ = writeln!(out, "Volume={source}:{}:{opts}", v.target);
    }

    if let Some(cmd) = &svc.health_cmd {
        let _ = writeln!(out, "HealthCmd={cmd}");
        let _ = writeln!(out, "HealthInterval=10s");
        let _ = writeln!(out, "HealthStartPeriod=15s");
        let _ = writeln!(out, "HealthOnFailure=kill");
        let _ = writeln!(out, "Notify=healthy");
    }

    if env == Env::Prod {
        let _ = writeln!(out, "AutoUpdate=registry");
    }
    out.push('\n');

    let _ = writeln!(out, "[Service]");
    let _ = writeln!(out, "Restart=on-failure");
    let _ = writeln!(out, "TimeoutStopSec=30");
    if let Some(cpu) = svc.resources.cpu {
        let _ = writeln!(out, "CPUQuota={}%", (cpu * 100.0).round() as u32);
    }
    if let Some(mem) = svc.resources.memory {
        let _ = writeln!(out, "MemoryMax={mem}");
    }
    if let Some(slice) = &ws.cpu_slice {
        let _ = writeln!(out, "Slice={slice}");
    }
    out.push('\n');

    if input.enabled {
        let _ = writeln!(out, "[Install]");
        let _ = writeln!(out, "WantedBy=default.target");
    }

    Ok(Unit {
        file_name: format!("{stem}.container"),
        content: out,
    })
}

fn kind_label(kind: ServiceKind) -> &'static str {
    match kind {
        ServiceKind::Stateless => "stateless",
        ServiceKind::Stateful => "stateful",
    }
}

fn volume_stem(env: Env, service: &Service, source: &str) -> String {
    format!("{}-{}", unit_stem(env, &service.name), source)
}

/// systemd `Environment=` values with spaces or quotes are double-quoted; `\` and `"` are escaped.
fn quote_env(v: &str) -> String {
    if v.is_empty()
        || v.chars()
            .any(|c| c.is_whitespace() || c == '"' || c == '\'' || c == '\\')
    {
        let escaped = v.replace('\\', "\\\\").replace('"', "\\\"");
        format!("\"{escaped}\"")
    } else {
        v.to_string()
    }
}

/// Convenience: whether a service's source needs a build step before rendering.
pub fn needs_build(service: &Service) -> bool {
    matches!(service.source, Source::Build { .. })
}

/// Short version label for a container name, derived from an image reference:
/// the tag (`postgres:16` → `16`), the start of a digest, or `latest`.
pub fn image_version(image: &str) -> String {
    let last = image.rsplit('/').next().unwrap_or(image);
    let raw = match last.split_once('@') {
        Some((_, digest)) => digest
            .trim_start_matches("sha256:")
            .get(..12)
            .unwrap_or(digest),
        None => match last.split_once(':') {
            Some((_, tag)) if !tag.is_empty() => tag,
            _ => "latest",
        },
    };
    let cleaned: String = raw
        .to_ascii_lowercase()
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '-' })
        .collect();
    cleaned.trim_matches('-').to_string()
}

#[cfg(test)]
mod tests {
    use super::*;
    use maurice_core::*;
    use std::net::Ipv4Addr;

    fn fixture() -> Workspace {
        let web = Service {
            name: "web".into(),
            kind: ServiceKind::Stateless,
            source: Source::Build {
                dockerfile: "Dockerfile".into(),
                context: ".".into(),
            },
            ports: vec![
                Port {
                    container_port: 3000,
                    published: None,
                },
                Port {
                    container_port: 9090,
                    published: Some(Published {
                        host_ip: Ipv4Addr::LOCALHOST.into(),
                        host_port: 19090,
                    }),
                },
            ],
            env: vec![
                EnvVar {
                    key: "NODE_ENV".into(),
                    value: EnvValue::Literal("production".into()),
                },
                EnvVar {
                    key: "DATABASE_URL".into(),
                    value: EnvValue::Ref("{{postgres.url}}".into()),
                },
                EnvVar {
                    key: "API_KEY".into(),
                    value: EnvValue::Secret("web_api_key".into()),
                },
                EnvVar {
                    key: "MOTD".into(),
                    value: EnvValue::Literal("hello world".into()),
                },
            ],
            volumes: vec![],
            resources: Resources {
                cpu: Some(0.5),
                memory: Some(512 * 1024 * 1024),
            },
            isolated: false,
            health_cmd: Some("curl -f http://localhost:3000/health".into()),
        };
        let pg = Service {
            name: "postgres".into(),
            kind: ServiceKind::Stateful,
            source: Source::Image {
                reference: "docker.io/library/postgres:16".into(),
            },
            ports: vec![Port {
                container_port: 5432,
                published: None,
            }],
            env: vec![EnvVar {
                key: "POSTGRES_PASSWORD".into(),
                value: EnvValue::Secret("pg_admin".into()),
            }],
            volumes: vec![Volume {
                source: "data".into(),
                target: "/var/lib/postgresql/data".into(),
                read_only: false,
            }],
            resources: Resources::default(),
            isolated: false,
            health_cmd: None,
        };
        Workspace {
            name: "shop".into(),
            unix_user: "ws-shop".into(),
            uid: 60001,
            subuid_start: 1_000_000,
            subuid_len: 65536,
            home: "/srv/ws/shop".into(),
            cpu_slice: Some("maurice-prod.slice".into()),
            environments: vec![Environment {
                env: Env::Prod,
                projects: vec![Project {
                    name: "storefront".into(),
                    git_repo: None,
                    services: vec![web, pg],
                }],
            }],
        }
    }

    fn web(ws: &Workspace) -> &Service {
        &ws.environments[0].projects[0].services[0]
    }

    fn pg(ws: &Workspace) -> &Service {
        &ws.environments[0].projects[0].services[1]
    }

    fn resolver(r: &str) -> Option<String> {
        match r {
            "{{postgres.url}}" => Some("postgres://app@postgres:5432/shop".into()),
            _ => None,
        }
    }

    #[test]
    fn network_unit() {
        let u = render_network(&fixture(), Env::Prod);
        assert_eq!(u.file_name, "shop-prod.network");
        assert!(u.content.contains("NetworkName=shop-prod"));
        let d = render_network(&fixture(), Env::Dev);
        assert_eq!(d.file_name, "shop-dev.network");
        // aardvark-dns is on by default; `DNS=` in Quadlet is a list of resolver IPs, never a flag.
        assert!(!u.content.contains("DNS="));
    }

    #[test]
    fn container_unit_for_web() {
        let ws = fixture();
        let web = web(&ws);
        let u = render_container(&RenderInput {
            workspace: &ws,
            env: Env::Prod,
            service: web,
            image: "registry.local/shop/web@sha256:abc",
            version: "a1b2c3",
            resolve_ref: &resolver,
            enabled: true,
        })
        .unwrap();
        let c = &u.content;
        assert_eq!(u.file_name, "prod-web.container");
        assert!(
            c.contains("ContainerName=prod-web-a1b2c3"),
            "container name carries the environment and the version"
        );
        assert!(c.contains("Network=shop-prod.network"));
        assert!(c.contains("NetworkAlias=web"), "alias is the stable name");
        assert!(c.contains("Label=maurice.environment=prod"));
        assert!(c.contains("Label=maurice.unit=prod-web"));
        assert!(c.contains("PublishPort=127.0.0.1:19090:9090"));
        assert!(
            !c.contains("3000:"),
            "unpublished port must not appear in PublishPort"
        );
        assert!(c.contains("Environment=DATABASE_URL=postgres://app@postgres:5432/shop"));
        assert!(c.contains("Environment=MOTD=\"hello world\""));
        assert!(c.contains("Secret=web_api_key,type=env,target=API_KEY"));
        assert!(
            !c.contains("Environment=API_KEY"),
            "secret values never inline"
        );
        assert!(c.contains("Notify=healthy"));
        assert!(
            c.contains("AutoUpdate=registry"),
            "prod enables auto-update"
        );
        assert!(c.contains("CPUQuota=50%"));
        assert!(c.contains("MemoryMax=536870912"));
        assert!(c.contains("Slice=maurice-prod.slice"));
        assert!(c.contains("LogDriver=journald"));
        assert!(c.contains("WantedBy=default.target"));
    }

    #[test]
    fn undeployed_service_has_no_install_section() {
        let ws = fixture();
        let u = render_container(&RenderInput {
            workspace: &ws,
            env: Env::Prod,
            service: web(&ws),
            image: "img",
            version: "v1",
            resolve_ref: &resolver,
            enabled: false,
        })
        .unwrap();
        assert!(!u.content.contains("[Install]"));
    }

    #[test]
    fn dev_environment_has_no_auto_update_and_its_own_network() {
        let ws = fixture();
        let u = render_container(&RenderInput {
            workspace: &ws,
            env: Env::Dev,
            service: web(&ws),
            image: "img",
            version: "v1",
            resolve_ref: &resolver,
            enabled: true,
        })
        .unwrap();
        assert_eq!(u.file_name, "dev-web.container");
        assert!(u.content.contains("Network=shop-dev.network"));
        assert!(!u.content.contains("AutoUpdate="));
    }

    #[test]
    fn stateful_volume_has_selinux_label() {
        let ws = fixture();
        let pg = pg(&ws);
        let u = render_container(&RenderInput {
            workspace: &ws,
            env: Env::Prod,
            service: pg,
            image: "docker.io/library/postgres@sha256:def",
            version: "16-4",
            resolve_ref: &resolver,
            enabled: true,
        })
        .unwrap();
        assert!(
            u.content
                .contains("Volume=prod-postgres-data.volume:/var/lib/postgresql/data:Z")
        );
        let vols = render_volumes(Env::Prod, pg);
        assert_eq!(vols.len(), 1);
        assert_eq!(vols[0].file_name, "prod-postgres-data.volume");
        assert!(vols[0].content.contains("VolumeName=prod-postgres-data"));
    }

    #[test]
    fn unresolved_ref_fails_rendering() {
        let ws = fixture();
        let err = render_container(&RenderInput {
            workspace: &ws,
            env: Env::Prod,
            service: web(&ws),
            image: "x",
            version: "v",
            resolve_ref: &|_| None,
            enabled: true,
        })
        .unwrap_err();
        assert_eq!(
            err,
            RenderError::UnresolvedRef {
                key: "DATABASE_URL".into(),
                reference: "{{postgres.url}}".into()
            }
        );
    }

    #[test]
    fn image_version_from_tag_digest_or_latest() {
        assert_eq!(image_version("docker.io/library/postgres:16"), "16");
        assert_eq!(
            image_version("docker.io/valkey/valkey:8-alpine"),
            "8-alpine"
        );
        assert_eq!(image_version("localhost:5000/shop/web:v1.2"), "v1-2");
        assert_eq!(image_version("ghcr.io/org/app"), "latest");
        assert_eq!(
            image_version("registry/web@sha256:abcdef0123456789aa"),
            "abcdef012345"
        );
    }

    #[test]
    fn rendering_is_deterministic() {
        let ws = fixture();
        let mk = || {
            render_container(&RenderInput {
                workspace: &ws,
                env: Env::Prod,
                service: web(&ws),
                image: "img",
                version: "v1",
                resolve_ref: &resolver,
                enabled: true,
            })
            .unwrap()
        };
        assert_eq!(mk(), mk());
    }
}
